#!/usr/bin/env node
/**
 * Generates `src/server/ui-shell.generated.ts` from canonical `src/ui/shell/*` source files.
 * Keeps the single official built-in Web UI version-locked inside `@meru-mind/core`
 * with zero runtime file-system fragility and zero manual string escaping drift.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const UI_DIR = path.join(ROOT, "src", "ui", "shell");
const OUT_FILE = path.join(ROOT, "src", "server", "ui-shell.generated.ts");

export function buildGeneratedUiShellTs() {
  const html = fs.readFileSync(path.join(UI_DIR, "index.html"), "utf8");
  const css = fs.readFileSync(path.join(UI_DIR, "styles.css"), "utf8");
  const js = fs.readFileSync(path.join(UI_DIR, "app.js"), "utf8");

  return [
    "// AUTO-GENERATED by scripts/generate-ui-assets.mjs from src/ui/shell/* — DO NOT EDIT MANUALLY.",
    "",
    `export const DEFAULT_SHELL_HTML = ${JSON.stringify(html)};`,
    "",
    `export const DEFAULT_SHELL_CSS = ${JSON.stringify(css)};`,
    "",
    `export const DEFAULT_SHELL_JS = ${JSON.stringify(js)};`,
    "",
  ].join("\n");
}

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const checkOnly = process.argv.includes("--check");
  const nextContent = buildGeneratedUiShellTs();
  if (checkOnly) {
    const existing = fs.existsSync(OUT_FILE)
      ? fs.readFileSync(OUT_FILE, "utf8")
      : "";
    if (existing !== nextContent) {
      process.stderr.write(
        "src/server/ui-shell.generated.ts is out of date with src/ui/shell/*. Run `node scripts/generate-ui-assets.mjs`.\n",
      );
      process.exit(1);
    }
    process.stdout.write("UI shell generated assets are in sync.\n");
  } else {
    fs.writeFileSync(OUT_FILE, nextContent, "utf8");
    process.stdout.write(
      `Generated src/server/ui-shell.generated.ts (${Buffer.byteLength(nextContent, "utf8")} bytes) from src/ui/shell/*.\n`,
    );
  }
}
